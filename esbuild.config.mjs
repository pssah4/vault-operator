// MCP Server worker — separate OS process (ADR-053)
const mcpWorkerContext = await esbuild.context({
    entryPoints: ["src/mcp/mcp-server-worker.ts"],
    bundle: true,
    external: [],        // Standalone Node.js, bundled with MCP SDK
    platform: "node",
    format: "cjs",
    target: "es2022",
    outfile: "mcp-server-worker.js",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    // This emitted source is embedded verbatim in main.js as a string.
    minify: prod,
    charset: "utf8",
});

if (prod) {
    // Workers first — they get inlined into main.js via generateInlineAssets
    await mcpWorkerContext.rebuild();
    // Emit src/_generated/bundled-*.ts files which the readers import.
    generateInlineAssets();
    // Emit plugin-source.json + source-hash.ts BEFORE the main esbuild
    // context is created so esbuild reads the freshly written SHA.
    await generateSourceBundle();
    // Build office-bundle.js + pdfjs-bundle.js + asset-bundle-hashes.ts
    // BEFORE main bundle, so main.js sees the fresh SHAs.
    await generateOfficeBundles();
    // Emit language-pack SHAs + release-asset copies BEFORE the main bundle
    // so locale-hashes.ts is compiled in (FEAT-42-05).
    generateLocaleHashes();
    // Typecheck AFTER generation, BEFORE the main bundle. A clean checkout has
    // no src/_generated/ yet (gitignored, written by the generators above), so
    // a tsc that runs first dies with TS2307 -- exactly what the community
    // review bot's build verification does (`npm run build` in a clean clone).
    // Running tsc here keeps the gate: a type error still blocks the bundle
    // emit and the vault deploy that hangs off it.
    execSync("npx tsc -noEmit -skipLibCheck", { stdio: "inherit" });
    // Single-shot build with up-to-date generated files
    await esbuild.build(mainBuildOptions);
    process.exit(0);
} else {
    try { generateInlineAssets(); } catch { /* workers not yet built — will be generated on first rebuild */ }
    try { await generateSourceBundle(); } catch { /* non-fatal during watch */ }
    try { await generateOfficeBundles(); } catch (e) { console.warn("[office-bundles] dev build skipped:", e.message); }
    try { generateLocaleHashes(); } catch (e) { console.warn("[locale-packs] dev build skipped:", e.message); }
    const context = await esbuild.context(mainBuildOptions);
    await context.watch();
    await mcpWorkerContext.watch();
}
